def _clone(state):
    new = copy.copy(state)
    for field in ("terrain", "city_owner", "is_capital", "outpost_upgrade", "city_placer",
                  "capital_settle_order", "army_faction", "army_units", "frozen", "locked",
                  "battle_faction", "battle_origin", "battle_units", "battle_moved",
                  "battle_round", "gold", "resources", "kill_xp", "victory_points", "alive"):
        setattr(new, field, getattr(state, field).copy())
    new.battle_order = list(state.battle_order)
    return new


def main():
    out = sys.stdout
    out_cases = []
    for name, build, cavalry_only, seed in SCENARIOS:
        s = blank_state()
        actions = build(s)
        before = _clone(s)
        after = _clone(s)
        apply_movement_step(after, actions, random.Random(seed), cavalry_only=cavalry_only)
        out_cases.append((name, seed, cavalry_only, actions, before, after))

    out.write(f"SCENARIOS {len(out_cases)}\n")
    for name, seed, cavalry_only, actions, before, after in out_cases:
        out.write(f"SCENARIO {name}\n")
        out.write(f"SEED {seed}\n")
        out.write(f"CAVALRY_ONLY {1 if cavalry_only else 0}\n")
        items = [(f, a) for f, a in actions.items() if a is not None]
        out.write(f"ACTIONS {len(items)}\n")
        for faction, (hex_index, direction) in items:
            out.write(f"{faction} {int(hex_index)} {int(direction)}\n")
        write_state(out, before)
        write_state(out, after)


if __name__ == "__main__":
    main()
