from state_io import write_state  # noqa: E402

RADIUS = 5
NUM_FACTIONS = 6
IMPASSABLE = (1, 2)  # mountain, lake


def blank_state(seed=7, terrain_flat=True):
    """A generated board with everything but terrain cleared. terrain_flat makes
    every hex plains, so scenarios can place armies anywhere without tripping over
    impassable tiles; scenarios that care about terrain set it explicitly."""
    s = create_initial_state(radius=RADIUS, num_factions=NUM_FACTIONS, seed=seed)
    if terrain_flat:
        s.terrain[:] = 0
    s.city_owner[:] = NO_FACTION
    s.is_capital[:] = False
    s.city_placer[:] = NO_FACTION
    s.army_faction[:] = NO_FACTION
    s.army_units[:] = 0
    s.frozen[:] = False
    s.locked[:] = False
    s.gold[:] = 0
    s.kill_xp[:] = 0
    return s


def put(s, hex_index, faction, inf=0, cav=0, arc=0):
    s.army_faction[hex_index] = faction
    s.army_units[hex_index] = [inf, cav, arc]


def nb(s, hex_index, direction):
    return int(s.grid.neighbor_table[hex_index, direction])


def find_chain(s, length):
    """A run of `length` hexes each adjacent to the next, all passable."""
    for start in range(s.num_hexes):
        for d in range(6):
            chain = [start]
            cur = start
            ok = True
            for _ in range(length - 1):
                nxt = nb(s, cur, d)
                if nxt < 0 or s.terrain[nxt] in IMPASSABLE:
                    ok = False
                    break
                chain.append(nxt)
                cur = nxt
            if ok and len(chain) == length and s.terrain[chain[0]] not in IMPASSABLE:
                return chain, d
    raise RuntimeError("no chain found")


def find_hub(s, spokes):
    """A hex with at least `spokes` passable neighbours; returns (hub, [(nbr, dir_to_hub)])."""
    for h in range(s.num_hexes):
        if s.terrain[h] in IMPASSABLE:
            continue
        found = []
        for d in range(6):
            j = nb(s, h, d)
            if j >= 0 and s.terrain[j] not in IMPASSABLE:
                back = None
                for d2 in range(6):
                    if nb(s, j, d2) == h:
                        back = d2
                if back is not None:
                    found.append((j, back))
        if len(found) >= spokes:
            return h, found[:spokes]
    raise RuntimeError("no hub found")


SCENARIOS = []


def scenario(name, cavalry_only=False, seeds=(1,)):
    def deco(fn):
        for seed in seeds:
            SCENARIOS.append((f"{name}#s{seed}", fn, cavalry_only, seed))
        return fn
    return deco


# --- Line Battles -----------------------------------------------------------

# Exact tie: the battle hex is decided by rng.random() < 0.5, the ONLY rng draw a
# movement step ever makes. Several seeds so both branches are taken.
@scenario("line_battle_tie", seeds=(1, 2, 3, 4, 5, 6))
def _(s):
    chain, d = find_chain(s, 2)
    a, b = chain
    put(s, a, 0, inf=3)
    put(s, b, 1, inf=3)
    back = next(d2 for d2 in range(6) if nb(s, b, d2) == a)
    return {0: (a, d), 1: (b, back)}


# Unequal armies: the SMALLER army's own hex hosts the fight. Both orderings, so a
# tie-break implemented backwards cannot pass by luck.
@scenario("line_battle_smaller_first")
def _(s):
    chain, d = find_chain(s, 2)
    a, b = chain
    put(s, a, 0, inf=1)
    put(s, b, 1, inf=5)
    back = next(d2 for d2 in range(6) if nb(s, b, d2) == a)
    return {0: (a, d), 1: (b, back)}


@scenario("line_battle_larger_first")
def _(s):
    chain, d = find_chain(s, 2)
    a, b = chain
    put(s, a, 0, inf=5)
    put(s, b, 1, inf=1)
    back = next(d2 for d2 in range(6) if nb(s, b, d2) == a)
    return {0: (a, d), 1: (b, back)}


# --- Encounter battles ------------------------------------------------------

@scenario("encounter_three_factions")
def _(s):
    hub, spokes = find_hub(s, 3)
    actions = {}
    for i, (nbr, dir_to_hub) in enumerate(spokes):
        put(s, nbr, i, inf=2)
        actions[i] = (nbr, dir_to_hub)
    return actions


@scenario("encounter_then_reinforce_locked")
def _(s):
    """Two factions collide on the hub (locking it); a third arrives the same step
    from elsewhere and joins as a reinforcement."""
    hub, spokes = find_hub(s, 3)
    actions = {}
    for i, (nbr, dir_to_hub) in enumerate(spokes[:3]):
        put(s, nbr, i, inf=2, cav=1)
        actions[i] = (nbr, dir_to_hub)
    return actions


