"""
Hand-built movement scenarios targeting the rare paths real games barely reach.

The full-turn traces (dump_turn_traces.py) cover ordinary play well - 103 of 180
turns contain a battle - but they give no evidence about the specific edge cases
that make movement.py the trickiest module to port:

  - Line Battle tie-breaks, including the EXACT-TIE coin flip, the only place a
    movement step consumes rng at all.
  - Overstacked peaceful merges reverting, and the two documented quirks in
    _revert_departure: reverting onto an origin another faction has since claimed
    (starts a battle there) and onto an origin an unrelated battle locked this
    same step (recreates a peaceful army on a locked hex).
  - Walking onto an undefended foreign capital or outpost, which now always forces
    a battle.
  - Reinforcing an already-locked hex, and pushing toward MAX_BATTLE_CONTRIB.

Each scenario is a hand-placed board, one movement step, and the resulting state -
generated by engine_old, replayed by the C++ engine.

Usage:  python engine/tools/dump_movement_scenarios.py > engine/tests/data/movement_scenarios.txt
"""

import copy
import os
