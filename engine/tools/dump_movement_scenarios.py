# --- Overstacking and the revert quirks --------------------------------------

@scenario("overstack_revert_simple")
def _(s):
    """5 + 4 into one hex exceeds the 6-unit cap: the move is illegal and the
    arriving army goes home untouched."""
    chain, d = find_chain(s, 2)
    a, b = chain
    put(s, a, 0, inf=5)
    put(s, b, 0, inf=4)
    return {0: (a, d)}


@scenario("overstack_revert_multi_arrival")
def _(s):
    hub, spokes = find_hub(s, 3)
    actions = {}
    for i, (nbr, dir_to_hub) in enumerate(spokes[:3]):
        put(s, nbr, 0 if i == 0 else i, inf=3)
        actions[0 if i == 0 else i] = (nbr, dir_to_hub)
    put(s, hub, 0, inf=1)
    return actions


@scenario("revert_onto_origin_claimed_by_enemy")
def _(s):
    """QUIRK: faction 0 overstacks and reverts, but faction 1 peacefully moved
    into 0's origin the same step - so the revert starts a battle there."""
    chain, d = find_chain(s, 3)
    a, b, c = chain
    put(s, a, 0, inf=5)   # a -> b, will overstack and revert
    put(s, b, 0, inf=4)
    put(s, c, 1, inf=2)   # c -> b? no: 1 moves into a, which 0 is vacating
    back = next(d2 for d2 in range(6) if nb(s, b, d2) == a)
    s.army_faction[c] = NO_FACTION
    s.army_units[c] = 0
    put(s, b, 0, inf=4)
    # faction 1 sits on b's far side and steps into a
    put(s, c, 1, inf=2)
    return {0: (a, d), 1: (c, back)} if nb(s, c, back) == b else {0: (a, d)}


@scenario("revert_onto_own_origin_merges")
def _(s):
    """Faction 0 moves a cavalry-only stack out and an overstacked move reverts
    onto the same origin, merging with what stayed behind."""
    chain, d = find_chain(s, 2)
    a, b = chain
    put(s, a, 0, inf=6)
    put(s, b, 0, inf=3)
    return {0: (a, d)}


